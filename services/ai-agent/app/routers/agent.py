# ── Server-Sent Events (SSE) Streaming Endpoints ──────────────

@router.post(
    "/stream",
    status_code=status.HTTP_200_OK,
    summary="Real-time Server-Sent Events (SSE) Recommendation Stream (POST)",
)
async def stream_recommendations_post(
    payload: StreamRequest,
):
    """
    Exposes a streaming SSE endpoint delivering real-time tokens generated by Google Gemini 3.8 Flash
    grounded in PostgreSQL live database state (recipes, waste logs, pantry deficits).
    Suitable for mobile/web clients using fetch with streaming bodies.
    """
    headers = {
        "Content-Type": "text/event-stream",
        "Cache-Control": "no-cache",
        "Connection": "keep-alive",
        "X-Accel-Buffering": "no",
    }
    return StreamingResponse(
        AgentService.stream_recommendations(payload),
        media_type="text/event-stream",
        headers=headers,
    )


@router.get(
    "/stream",
    status_code=status.HTTP_200_OK,
    summary="Real-time Server-Sent Events (SSE) Recommendation Stream (GET)",
)
async def stream_recommendations_get(
    organization_id: str = Query(..., description="UUID of the organization / hotel client"),
    prompt: Optional[str] = Query(None, description="Custom chef query or instructions"),
    stream_type: str = Query(
        "prep_forecast",
        description="Stream mode: 'prep_forecast', 'inventory_eval', or 'chef_assistant'"
    ),
    day_of_week: Optional[str] = Query(None, description="Day of week override, e.g. 'Friday'"),
    use_live_db: bool = Query(True, description="Query PostgreSQL database for real inventory/recipes"),
):
    """
    Exposes a GET streaming SSE endpoint compatible with native browser and mobile `EventSource`.
    Delivers real-time tokens from Google Gemini 3.8 Flash grounded in PostgreSQL database state.
    """
    payload = StreamRequest(
        organization_id=organization_id,
        prompt=prompt,
        stream_type=stream_type,
        day_of_week=day_of_week,
        use_live_db=use_live_db,
    )
    headers = {
        "Content-Type": "text/event-stream",
        "Cache-Control": "no-cache",
        "Connection": "keep-alive",
        "X-Accel-Buffering": "no",
    }
    return StreamingResponse(
        AgentService.stream_recommendations(payload),
        media_type="text/event-stream",
        headers=headers,
    )

